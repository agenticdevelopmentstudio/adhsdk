// The text of src/theme-data.ts for a styles directory: one string-literal export per
// `*.css` file, keyed by camelized basename, each with its relative @imports inlined.
// build-theme-data.mjs writes it; the theme-data sync test compares it with the file on
// disk, so the generator and the check can never disagree about what "in sync" means.
// Ships beside build-theme-data.mjs (package.json `files`): postinstall imports it.
import { readdir } from 'node:fs/promises'
import { join } from 'node:path'
import { inlineImports } from './inline-imports.mjs'

function camelize(name) {
  return name.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
}

export async function renderThemeData(stylesDir) {
  const files = (await readdir(stylesDir)).filter((f) => f.endsWith('.css')).sort()
  const lines = ['// AUTO-GENERATED by scripts/build-theme-data.mjs — do not edit.', '']
  for (const file of files) {
    const css = await inlineImports(join(stylesDir, file))
    const varName = `${camelize(file.replace(/\.css$/, ''))}Css`
    lines.push(`export const ${varName} = ${JSON.stringify(css)}`)
  }
  lines.push('')
  return { text: lines.join('\n'), count: files.length }
}
